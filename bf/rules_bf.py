# -*- coding: utf-8 -*-
"""BF-интерпретатор как система переписывания Маркова.

Единственный источник правды для правил. Каждый шаг исполнения BF —
применение ПЕРВОГО совпавшего правила (по порядку) к строке-состоянию.

Формат состояния (одна строка, printable ASCII):
    BF1|ST:run|C:^<код>|T:@00|D:0123456789abcdef|IN:<hex>|OUT:<hex>|

  C:  код BF, маркер ^ стоит ПЕРЕД следующей исполняемой инструкцией
  T:  лента: ячейки по 2 hex-цифры через пробел, @ перед текущей ячейкой
  D:  константная таблица преемников цифр (lookup внутри состояния)
  IN: очередь ввода (hex-байты), OUT: вывод (hex-байты)
  ST: run | hlt | err:<КОД>

Инварианты против катастрофического бэктрекинга:
  - каждый паттерн заякорен \\A и начинается литералом BF1|ST:run| —
    несовпавшее правило отваливается за O(1) попыток;
  - квантификаторы possessive (*+, ++), классы взаимоисключающие;
  - единственный неpossessive квантификатор — [^@]* в left (откат ровно
    на 3 символа) и ленивые префиксы в rbracket (ограничены числом '[').

Синтаксис: PCRE2-совместимый; replacement в синтаксисе PCRE2 (${n});
proto-драйвер транслирует ${n} -> \\g<n> для Python-модуля regex.
"""

PRE = r"\ABF1\|ST:run\|C:"     # общий якорь-гейт
REP = "BF1|ST:run|C:"          # префикс re-emit в replacement

# Порядок критичен: первое совпавшее правило применяется (алгоритм Маркова).
RULES = [
    # --- останов: IP упёрся в конец кода ---
    ("halt",
     PRE + r"([^^]*+)\^\|T:",
     "BF1|ST:hlt|C:${1}^|T:"),

    # --- '+' : инкремент ячейки (3 правила покрывают все 256 значений) ---
    ("plus_ff",                # ff -> 00
     PRE + r"([^^]*+)\^\+([^@]*+@)ff",
     REP + "${1}+^${2}00"),
    ("plus_carry",             # xf -> (succ x)0, x != f
     PRE + r"([^^]*+)\^\+([^@]*+@)([0-9a-e])f(?=[^|]*+\|D:[0-9a-f]*?\3([0-9a-f]))",
     REP + "${1}+^${2}${4}0"),
    ("plus",                   # xy -> x(succ y), y != f
     PRE + r"([^^]*+)\^\+([^@]*+@[0-9a-f])([0-9a-e])(?=[^|]*+\|D:[0-9a-f]*?\3([0-9a-f]))",
     REP + "${1}+^${2}${4}"),

    # --- '-' : декремент (симметрично, предшественник = цифра перед y в D) ---
    ("minus_00",               # 00 -> ff
     PRE + r"([^^]*+)\^-([^@]*+@)00",
     REP + "${1}-^${2}ff"),
    ("minus_borrow",           # x0 -> (pred x)f, x != 0
     PRE + r"([^^]*+)\^-([^@]*+@)([1-9a-f])0(?=[^|]*+\|D:[0-9a-f]*?([0-9a-f])\3)",
     REP + "${1}-^${2}${4}f"),
    ("minus",                  # xy -> x(pred y), y != 0
     PRE + r"([^^]*+)\^-([^@]*+@[0-9a-f])([1-9a-f])(?=[^|]*+\|D:[0-9a-f]*?([0-9a-f])\3)",
     REP + "${1}-^${2}${4}"),

    # --- '>' : вправо ---
    ("right",                  # @xx yy -> xx @yy
     PRE + r"([^^]*+)\^>([^@]*+)@([0-9a-f]{2}) ",
     REP + "${1}>^${2}${3} @"),
    ("right_grow",             # @xx|D: -> xx @00|D:  (лента растёт)
     PRE + r"([^^]*+)\^>([^@]*+)@([0-9a-f]{2})\|D:",
     REP + "${1}>^${2}${3} @00|D:"),

    # --- '<' : влево ---
    ("left_edge",              # выход за левый край -> трап
     r"\ABF1\|ST:run(\|C:[^^]*+)\^<((?:[+\-<>.,\[\]])*+\|T:)@",
     "BF1|ST:err:TAPE${1}^<${2}@"),
    ("left",                   # xx @yy -> @xx yy
     PRE + r"([^^]*+)\^<([^@]*)([0-9a-f]{2}) @",
     REP + "${1}<^${2}@${3} "),

    # --- '.' : вывод ячейки в OUT ---
    ("dot",
     PRE + r"([^^]*+)\^\.([^@]*+@)([0-9a-f]{2})([^|]*+\|D:[0-9a-f]*+\|IN:[0-9a-f]*+\|OUT:[0-9a-f]*+)\|",
     REP + "${1}.^${2}${3}${4}${3}|"),

    # --- ',' : ввод из IN (или 00 при EOF) ---
    ("comma_in",
     PRE + r"([^^]*+)\^,([^@]*+@)[0-9a-f]{2}([^|]*+\|D:[0-9a-f]*+\|IN:)([0-9a-f]{2})",
     REP + "${1},^${2}${4}${3}"),
    ("comma_eof",
     PRE + r"([^^]*+)\^,([^@]*+@)[0-9a-f]{2}(?=[^|]*+\|D:[0-9a-f]*+\|IN:\|)",
     REP + "${1},^${2}00"),

    # --- '[' : вход в цикл / пропуск сбалансированного блока ---
    ("lbracket_enter",         # ячейка != 00 -> шаг внутрь
     PRE + r"([^^]*+)\^\[(?=[^@]*+@(?!00))",
     REP + "${1}[^"),
    ("lbracket_skip",          # ячейка == 00 -> IP за парную ']' (рекурсия)
     PRE + r"([^^]*+)\^(\[(?:[+\-<>.,]++|(?2))*+\])(?=[^@]*+@00)",
     REP + "${1}${2}^"),

    # --- ']' : безусловный прыжок назад к парной '[' (она перетестирует) ---
    ("rbracket",
     PRE + r"([^^]*?)\[((?:[+\-<>.,]++|\[(?2)\])*+)\^\]",
     REP + "${1}^[${2}]"),

    # --- catch-all: гарантия тотальности (обязан быть ПОСЛЕДНИМ) ---
    ("wedge",
     r"\ABF1\|ST:run\|",
     "BF1|ST:err:WEDGE|"),
]

BF_CHARS = set("+-<>.,[]")


def make_state(code: str, input_bytes: bytes = b"") -> str:
    """BF-исходник -> начальная строка-состояние."""
    prog = "".join(ch for ch in code if ch in BF_CHARS)
    depth = 0
    for ch in prog:
        if ch == "[":
            depth += 1
        elif ch == "]":
            depth -= 1
            if depth < 0:
                raise ValueError("несбалансированные скобки в BF-программе")
    if depth != 0:
        raise ValueError("несбалансированные скобки в BF-программе")
    return (
        "BF1|ST:run|C:^" + prog + "|T:@00|D:0123456789abcdef"
        "|IN:" + input_bytes.hex() + "|OUT:|"
    )
