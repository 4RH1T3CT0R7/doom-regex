/* G1c-демо: анимированные диагональные волны в фреймбуфере RegexVM.
 * Окно FB: слова по адресам 0xf00000..0xf007ff (64x32, байт на пиксель).
 * Без умножений/битовых операций: только ADD/SUB/сравнения (иначе 8cc
 * развернёт builtins в bit-serial циклы). */

int main() {
    int t;
    for (t = 0; t < 6; t++) {
        int p = 0xf00000;
        int y;
        int c0 = t + t;                 /* фаза кадра */
        for (y = 0; y < 32; y++) {
            int x;
            int c = c0 + y;
            for (x = 0; x < 64; x++) {
                while (c >= 240) c -= 240;    /* wrap без AND */
                *(int *)p = 16 + c;           /* градиентная зона палитры */
                p = p + 1;
                c = c + 3;
            }
        }
    }
    return 0;
}
