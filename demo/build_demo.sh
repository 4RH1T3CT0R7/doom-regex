#!/usr/bin/env bash
# Сборка скачиваемого демо-пакета (папка dist/doom-regex-demo):
#   doomregex_demo.exe (вьювер-лаунчер, Win32/GDI, без зависимостей)
#   rvm.exe            (честная машина: цикл pcre2_substitute)
#   rules_rvm.rgxset   (544 правила, sha256 проверяется при загрузке)
#   snapshot.rvstate   (строка-состояние у входа в рендер кадра E1M1)
#   README.txt
set -euo pipefail

REPO="$(cd "$(dirname "$0")/.." && pwd)"
OUT="${DOOMREGEX_OUT:-/c/dev/doom-regex-out}"
DIST="$OUT/dist/doom-regex-demo"
SNAP="${1:-$OUT/run/g2d_fb_snapshot.rvstate}"

export TMP="$OUT/tmp" TEMP="$OUT/tmp"
mkdir -p "$OUT/tmp" "$DIST"

# зеркалим исходник вьювера в ASCII-путь (кириллица в пути ломает gcc)
mkdir -p "$OUT/build/src/demo"
cp "$REPO/demo/viewer/doomregex_demo.c" "$REPO/demo/viewer/playpal.h" \
   "$OUT/build/src/demo/"

/c/msys64/mingw64/bin/gcc -O2 -Wall -mwindows \
    -o "$DIST/doomregex_demo.exe" \
    "$OUT/build/src/demo/doomregex_demo.c" -lgdi32

cp "$OUT/build/rvm.exe" "$DIST/"
cp "$REPO/vm/rules_rvm.rgxset" "$DIST/"
[ -f "$SNAP" ] && cp "$SNAP" "$DIST/snapshot.rvstate" \
    || echo "ВНИМАНИЕ: снапшот не найден ($SNAP) - положи snapshot.rvstate руками"
# второй режим демо: наблюдение рендера одного кадра до фикс-точки
FRAME_SNAP="${2:-$OUT/run/g2d_v20_snapshot.rvstate}"
[ -f "$FRAME_SNAP" ] && cp "$FRAME_SNAP" "$DIST/snapshot_frame.rvstate" || echo "нет снапшота кадра"

cat > "$DIST/README.txt" <<'EOF'
DOOM, посчитанный заменой текста
================================

Запустить просто: двойной клик по doomregex_demo.exe, ничего
устанавливать не нужно.

Перед вами настоящая машина, у которой есть одна-единственная операция:
глобальная regex-подстановка над строкой в 96,6 мегабайта. В этой строке
обычным текстом лежит всё сразу: регистры, память, программа (сам DOOM,
скомпилированный в самодельную систему команд) и видеозона. Драйвер
раз за разом применяет к строке фиксированный набор из 544 правил
поиска-замены, и какое правило совпало первым, то один раз и
срабатывает. Окно показывает кадр, который машина рисует прямо сейчас,
и ленту подстановок: какое правило сработало, что оно съело и что
записало взамен.

В это можно играть. WASD или стрелки двигают игрока, Ctrl стреляет,
пробел открывает двери, Esc и Enter работают в меню. Каждое нажатие
дописывается в файл input.bin, откуда машина сама забирает его своей
инструкцией GETC, так что драйвер к управлению отношения не имеет.
Кадр считается около шести минут, поэтому играть придётся вдумчиво:
нажали, подождали, посмотрели, что изменилось.

При запуске демо спрашивает, что показать. Ответ «да» запускает игру,
ответ «нет» - наблюдение за тем, как машина рисует один кадр и
останавливается. Лента показывает одну подстановку из каждых 1200:
снимать состояние на каждой из них можно, но машина от этого
замедляется почти в двадцать раз.

В комплекте: doomregex_demo.exe (окно-наблюдатель), rvm.exe (сама
машина), rules_rvm.rgxset (правила, их хеш проверяется при загрузке),
snapshot.rvstate (строка-состояние на момент начала уровня) и
snapshot_frame.rvstate (то же самое для режима наблюдения).

Проект целиком: https://github.com/4RH1T3CT0R7/doom-regex
EOF

echo "OK: $DIST"
ls -la "$DIST"
